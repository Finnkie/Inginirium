def home_location(index):
    """Домашняя локация игрока по его номеру в ростере сервера."""
    kind = HOME_PATTERN[index % 11]
    if kind == "мир":
        return OPEN_WORLD
    names = LOCATION_TYPES[kind]
    return names[((index // 11) + (index % 11) - _SLOT_OF_KIND[kind]) % len(names)]


