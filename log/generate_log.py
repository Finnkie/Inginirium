NICK_RE = re.compile(r"^[А-ЯЁа-яё0-9\[\]\<\>\(\)\']+$")


def clamp(lo, hi, value):
    return max(lo, min(hi, value))


def validate_world():
    """Проверяем правила мира до генерации: ники, размеры, роли на своих местах."""
    seen = {}
    for server, spec in ROSTERS.items():
        names = spec["names"]
        assert 66 <= len(names) <= 99 and len(names) % 11 == 0, (
            f"{server}: игроков {len(names)}, нужно 66-99 и кратно 11"
        )
        for i, nick in enumerate(names):
            assert NICK_RE.match(nick), f"Ник с запрещёнными символами: {nick!r}"
            assert nick not in seen, (
                f"Ник не уникален: {nick} ({seen[nick]} и {server})"
            )
            seen[nick] = server
        villain, traders, beggars = spec["villain"], spec["traders"], spec["beggars"]
        assert names.index(villain) % 11 in (3, 4, 5), (
            f"{server}: злодей {villain} не в столице"
        )
        for t in traders:
            assert names.index(t) % 11 in (6, 7), (
                f"{server}: торговец {t} не в городских слотах"
            )
        assert len(beggars) == 4, f"{server}: попрошаек должно быть 4"
        assert sum(1 for b in beggars if names.index(b) % 11 in (4, 5)) == 2, (
            f"{server}: попрошаек в столице должно быть 2"
        )
        assert sum(1 for b in beggars if names.index(b) % 11 == 8) == 2, (
            f"{server}: попрошаек в деревне должно быть 2"
        )
        roles = {villain, *traders, *beggars}
        for slot, who in (
            (11, "чемпион танцев"),
            (12, "влюблённый"),
            (13, "предмет любви"),
        ):
            assert names[slot] not in roles, (
                f"{server}: {who} не должен быть сюжетной ролью"
            )
    texts = (
        SAY_MESSAGES
        + LS_MESSAGES
        + CLIENT_PM
        + TRADER_CHAT
        + TRADER_CLIENT_PM
        + BEG_WHINES
        + VILLAIN_ROOT_SHOUTS
        + VILLAIN_ENCRYPTED_SHOUTS
    )
    for text in texts:
        assert '"' not in text, f"Кавычки внутри сообщения ломают формат: {text!r}"
        assert " - " not in text, (
            f"Разделитель ' - ' внутри сообщения ломает формат: {text!r}"
        )


def random_event(rng, server, names, homes, roles):
    """Случайное событие рядового игрока (роли тоже живут обычной жизнью)."""
    nick = rng.choice(names)
    home = homes[nick]
    role = roles.get(nick, "normal")
    if role == "villain":
        loc = home  # злодей весь день стоит в столице
    elif role == "trader":
        # торговцы работают там, где покупатели, изредка выбираясь в провинцию
        loc = (
            rng.choice(TRADE_LOCATIONS)
            if rng.random() < 0.7
            else rng.choice(ALL_LOCATIONS)
        )
    else:
        stay = 0.9 if role == "beggar" else 0.8
        loc = home if rng.random() < stay else rng.choice(ALL_LOCATIONS)
    roll = rng.random()
    if roll < 0.32:
        return (server, loc, nick, "сказал", None, rng.choice(SAY_MESSAGES))
    if roll < 0.332:
        target = rng.choice(names)
        while target == nick:
            target = rng.choice(names)
        return (server, loc, nick, "написал_в_лс", target, rng.choice(LS_MESSAGES))
    if roll < 0.337:
        target = rng.choice(names)
        while target == nick:
            target = rng.choice(names)
        return (server, loc, nick, "обмен", target, None)
    if roll < 0.49:
        action = rng.choice(TARGET_ACTIONS_OTHER)
        if action == "вылечил" and rng.random() < 0.3:
            target = nick  # полечил сам себя
        elif action == "ударил" and rng.random() < 0.4:
            target = rng.choice(MONSTERS)
        else:
            target = rng.choice(names)
            while target == nick:
                target = rng.choice(names)
        return (server, loc, nick, action, target, None)
    return (server, loc, nick, rng.choice(NEUTRAL_ACTIONS), None, None)


def place_block(events, start, block):
    """Вставляем сюжетный блок в свободные слоты, не затирая чужие события."""
    n = len(events)
    i = start
    while i + len(block) <= n and any(
        events[i + k] is not None for k in range(len(block))
    ):
        i += 1
    if i + len(block) > n:
        return False
    for k, event in enumerate(block):
        events[i + k] = event
    return True


def build_server_events(rng, server, per_lines):
    """События одного сервера: сюжетные блоки + случайный фон. Возвращает
    (события, пометки для ведущего, доп. информация)."""
    spec = ROSTERS[server]
    names = spec["names"]
    homes = {nick: home_location(i) for i, nick in enumerate(names)}
    villain, traders, beggars = (
        spec["villain"],
        list(spec["traders"]),
        list(spec["beggars"]),
    )
    roles = {villain: "villain"}
    for t in traders:
        roles[t] = "trader"
    for b in beggars:
        roles[b] = "beggar"
    normals = [n for n in names if n not in roles]
    vh = homes[villain]

    events = [None] * per_lines
    marks = []

    def put(frac, block, kind=None):
        if place_block(events, int(frac * per_lines), block) and kind:
            for event in block:
                marks.append((event, kind))

    # 1. Злодей кричит о золоте (часть криков - "шифровки" без корня золот/голд)
    shouts = VILLAIN_ROOT_SHOUTS + VILLAIN_ENCRYPTED_SHOUTS
    rng.shuffle(shouts)
    # Реплик в крик уходит 10 из 13 (шифровок в списке всего 5), поэтому злодею
    # гарантированно достаётся хотя бы 5 "золотых" намёков - он не выпадет
    # из фильтра Шага 1 ("сказал" + "золот"). Верхний предел = длина списка.
    n_shouts = clamp(10, len(shouts), per_lines // 13000)
    for i in range(n_shouts):
        put(
            (i + 0.5) / n_shouts,
            [(server, vh, villain, "сказал", None, shouts[i])],
            "shout",
        )

    # 2. Клиенты стучатся злодею в лс и меняются с ним (много разных людей!)
    n_vp = clamp(2, 60, per_lines // 3000)
    for i, client in enumerate(rng.sample(normals, n_vp)):
        put(
            0.03 + 0.9 * i / max(1, n_vp),
            [
                (
                    server,
                    homes[client],
                    client,
                    "написал_в_лс",
                    villain,
                    rng.choice(CLIENT_PM),
                ),
                (server, vh, villain, "обмен", client, None),
            ],
        )

    # 3. Финальная сделка: крик -> лс покупателя -> сайт -> оплата -> обмен
    buyer = rng.choice(normals)
    order = rng.randint(100, 999)
    put(
        0.60,
        [
            (
                server,
                vh,
                villain,
                "сказал",
                None,
                "работаю как обычно, кто в курсе, тот в лс",
            ),
            (server, vh, buyer, "написал_в_лс", villain, "надёжно? не забанят?"),
            (
                server,
                vh,
                villain,
                "написал_в_лс",
                buyer,
                f"золото-базар.рф, заказ номер {order}, оплата вперёд",
            ),
            (
                server,
                vh,
                buyer,
                "написал_в_лс",
                villain,
                f"оплатил, заказ {order}, принимай",
            ),
            (server, vh, villain, "обмен", buyer, None),
        ],
        "deal",
    )

    # 4. Торговцы-шум: тоже часто меняются, часть говорит про золото в чате
    n_tp = clamp(2, 30, per_lines // 6000)
    n_chat = clamp(2, 12, per_lines // 15000)
    for ti, trader in enumerate(traders):
        for i, client in enumerate(rng.sample(normals, n_tp)):
            put(
                0.05 + 0.88 * i / max(1, n_tp),
                [
                    (
                        server,
                        homes[client],
                        client,
                        "написал_в_лс",
                        trader,
                        rng.choice(TRADER_CLIENT_PM),
                    ),
                    (
                        server,
                        rng.choice(TRADE_LOCATIONS),
                        trader,
                        "обмен",
                        client,
                        None,
                    ),
                ],
            )
        for i in range(n_chat):
            put(
                (i + 0.5) / n_chat,
                [
                    (
                        server,
                        rng.choice(ALL_LOCATIONS),
                        trader,
                        "сказал",
                        None,
                        TRADER_CHAT[(i + ti) % len(TRADER_CHAT)],
                    )
                ],
            )

    # 5. Попрошайки клянчат золото в столицах и деревнях (шум для шага 3)
    n_wh = clamp(2, 25, per_lines // 7000)
    for bi, beg in enumerate(beggars):
        for i in range(n_wh):
            frac = ((i + 0.5) / n_wh + bi / len(beggars)) % 0.98
            put(
                frac,
                [
                    (
                        server,
                        homes[beg],
                        beg,
                        "сказал",
                        None,
                        BEG_WHINES[(i + bi) % len(BEG_WHINES)],
                    )
                ],
            )

    # 6. Чемпион по танцам: танцует весь день и всюду
    dancer = names[11]
    n_dances = max(3, per_lines // 500)
    for i in range(n_dances):
        put(
            (i + 0.5) / n_dances,
            [(server, rng.choice(ALL_LOCATIONS), dancer, "станцевал", None, None)],
        )

    # 7. Романтическая история: потанцевал -> признался в любви
    lover, in_love_with = names[12], names[13]
    put(
        0.80,
        [
            (server, homes[lover], lover, "станцевал", None, None),
            (server, homes[lover], lover, "признался_в_любви", in_love_with, None),
            (server, homes[lover], in_love_with, "засмеялся", None, None),
            (
                server,
                homes[lover],
                in_love_with,
                "сказал",
                None,
                "ой, вот это поворот!",
            ),
        ],
    )

    # 8. Заполняем остаток рядовыми событиями
    for i, event in enumerate(events):
        if event is None:
            events[i] = random_event(rng, server, names, homes, roles)

    info = {
        "buyer": buyer,
        "dancer": dancer,
        "lover": lover,
        "in_love_with": in_love_with,
        "villain_home": vh,
    }
    return events, marks, info


def fmt_time(dt):
    return (
        f"[{dt.day:02d}/{MONTHS[dt.month]}/{dt.year}:"
        f"{dt.hour:02d}:{dt.minute:02d}:{dt.second:02d} +0300]"
    )


def fmt_line(dt, event):
    """Строка лога: 7 полей через ' - ', пропущенные поля - прочерк."""
    server, loc, nick, action, target, message = event
    loc = LOCATION_TAG.get(loc, loc)
    target = f"<{target}>" if target is not None else "-"
    message = f'"{message}"' if message is not None else "-"
    return " - ".join(
        [
            fmt_time(dt),
            server,
            loc,
            f"<{nick}>",
            f'"{action}"',
            target,
            message,
        ]
    )


def generate(lines, seed, out_path):
    rng = random.Random(seed)
    validate_world()
    assert lines >= 400, "слишком мало строк: нужно хотя бы 400 (сюжет не поместится)"

    # Ровное распределение строк по серверам
    per = [lines // len(SERVERS)] * len(SERVERS)
    for i in range(lines % len(SERVERS)):
        per[i] += 1

    server_events, infos, mark_index = {}, {}, {}
    for idx, server in enumerate(SERVERS):
        events, marks, info = build_server_events(rng, server, per[idx])
        server_events[server] = events
        infos[server] = info
        for event, kind in marks:
            mark_index[id(event)] = (server, kind)

    # Перемешиваем слоты серверов: все 6 серверов вперемешку, но счёт ровный
    slots = []
    for idx, server in enumerate(SERVERS):
        slots.extend([idx] * per[idx])
    rng.shuffle(slots)

    cursors = [0] * len(SERVERS)
    found = collections.defaultdict(list)
    written = 0

    with open(out_path, "w", encoding="utf-8") as f:
        for si in slots:
            server = SERVERS[si]
            idx = cursors[si]
            cursors[si] = idx + 1
            event = server_events[server][idx]
            # весь лог укладывается ровно в один игровой день: 86 400 секунд
            dt = START_TIME + timedelta(seconds=(written * 86400) // lines)
            f.write(fmt_line(dt, event) + "\n")
            written += 1
            tag = mark_index.get(id(event))
            if tag:
                found[tag].append(written)

    # Статистика по ролям (из событий, ещё до записи)
    exch = {s: collections.Counter() for s in SERVERS}
    pm = {s: collections.defaultdict(set) for s in SERVERS}
    gold = {s: collections.Counter() for s in SERVERS}
    dance = {s: collections.Counter() for s in SERVERS}
    for server in SERVERS:
        for _, _, nick, action, target, message in server_events[server]:
            if action == "обмен":
                exch[server][nick] += 1
            elif action == "написал_в_лс" and target is not None:
                pm[server][target].add(nick)
            elif (
                action == "сказал"
                and message
                and ("золот" in message or "голд" in message)
            ):
                gold[server][nick] += 1
            elif action == "станцевал":
                dance[server][nick] += 1

    size_mb = os.path.getsize(out_path) / 1024 / 1024
    print(f"Готово: {out_path}")
    print(f"  строк: {written}, размер: {size_mb:.1f} МБ, seed: {seed}")
    print("  события: один игровой день, 9 мая 2026 с 00:00 до 23:59")
    for idx, server in enumerate(SERVERS):
        mark = ""
        if lines > 20000 and not 180000 <= per[idx] <= 250000:
            mark = "  (!) для урока нужно 180-250 тыс. на сервер: запускайте --lines 1100000"
        print(
            f"  {server}: игроков {len(ROSTERS[server]['names'])}, событий {per[idx]}{mark}"
        )

    print("\n=== ОТВЕТЫ ДЛЯ ВЕДУЩЕГО (в файл не попадают) ===")
    for server in SERVERS:
        spec = ROSTERS[server]
        info = infos[server]
        villain = spec["villain"]
        vhome = LOCATION_TAG[info["villain_home"]]
        shout_lines = found.get((server, "shout"), [])
        deal_lines = found.get((server, "deal"), [])
        print(f"{server}: злодей {villain}, весь день стоит в {vhome}")
        print(
            f"  криков всего: {len(shout_lines)} (часть - шифровки без слова 'золот'), "
            f"строки: {shout_lines}"
        )
        print(
            f"  сделка с покупателем {info['buyer']} (крик->лс->сайт->оплата->обмен), "
            f"строки: {deal_lines}"
        )
        print(
            f"  стучались в ЛС: {len(pm[server][villain])} разных игроков, "
            f"обменов: {exch[server][villain]}, упоминаний золота в чате: {gold[server][villain]}"
        )
        print(
            f"  торговцы-шум: "
            + ", ".join(
                f"{t} (обменов {exch[server][t]}, ЛС от {len(pm[server][t])})"
                for t in spec["traders"]
            )
        )
        print(
            f"  попрошайки: {', '.join(spec['beggars'])} "
            f"(клянчат золото, обменов мало: "
            + ", ".join(str(exch[server][b]) for b in spec["beggars"])
            + ")"
        )
        print(
            f"  чемпион танцев: {info['dancer']} ({dance[server][info['dancer']]} раз); "
            f"любовь: {info['lover']} -> {info['in_love_with']}"
        )
    print("\nПодсказка для урока: после фильтров (3)+(4) остаются злодей и 3 торговца,")
    print(
        "после (6) злодей первый по уникальным авторам ЛС, после (7) он единственный,"
    )
    print(
        "кто весь день не выходит из столицы. Ориентиры: обменов >= 40, ЛС-авторов >= 70."
    )


def main():
    parser = argparse.ArgumentParser(
        description="Генератор игрового лога «Найди шпиона»"
    )
    parser.add_argument(
        "--lines",
        type=int,
        default=1000,
        help="всего строк (для урока: 1100000, по ~183 тыс. на сервер)",
    )
    parser.add_argument(
        "--seed", type=int, default=42, help="зерно генератора (уникальный лог)"
    )
    parser.add_argument("--out", default=None, help="путь к файлу лога")
    args = parser.parse_args()

    # Генератор лежит в log/ рядом с большим логом. Пути по умолчанию:
    # сэмпл (до 100 тыс. строк) - в папку мастер-класса, его читает spy_tools.LOG;
    # большой лог - рядом с генератором, в log/: ученики не должны найти его
    # в папке урока, иначе VS Code зависнет от такого файла.
    here = os.path.dirname(os.path.abspath(__file__))
    sample = os.path.normpath(
        os.path.join(here, "..", "mk_spy_parser", "masterclass", "game_server.log")
    )
    if args.out:
        out = args.out
    elif args.lines > 100_000:
        out = os.path.join(here, "game_server_full.log")
    else:
        out = sample
    generate(args.lines, args.seed, out)


if __name__ == "__main__":
    main()
