#
#   Кто-то на твоём сервере продаёт игровое золото за НАСТОЯЩИЕ деньги.
#   Найди его по логам игрового сервера за 9 мая!
#
#   Каждая строка лога состоит из 7 полей, разделённых " - "
#   (пробел-тире-пробел). Вот строка и её кусочки после split(" - "):
#
#   [09/May/2026:00:00:58 +0300] - Голд[Мир] - Белоград(столица) - <ДобрыйЖук> - "сказал" - - - "продам золото дёшево"
#
#      поля[0] = [09/May/2026:00:00:58 +0300]  ВРЕМЯ
#      поля[1] = Голд[Мир]                     СЕРВЕР
#      поля[2] = Белоград(столица)             ЛОКАЦИЯ (тип - в скобках!)
#      поля[3] = <ДобрыйЖук>                   ИГРОК (в скобках <>)
#      поля[4] = "сказал"                      ДЕЙСТВИЕ (в кавычках)
#      поля[5] = -                             ЦЕЛЬ (или прочерк)
#      поля[6] = "продам золото дёшево"        СООБЩЕНИЕ (в кавычках)
#
#   План расследования:
#      1) оставляем только строки НАШЕГО сервера
#      2) оставляем только столицы и города
#      3) кто говорил про золото?  <- там ШУМ, злодей прячется!
#      4) кто часто делает "обмен"?
#      5) пересекаем 3 и 4 -> подозреваемые
#      6) кому пишут в лс больше всех?
#      7) досье: кто весь день не выходит из столицы? -> ЗЛОДЕЙ!
# ==========================================================================


# --------------------------------------------------------------------------
# ИНСТРУМЕНТ СЫЩИКА (уже готов, трогать не нужно)
# --------------------------------------------------------------------------

def топ(словарь, сколько=5):
    """Из словаря {имя: число} возвращает топ самых-самых."""
    return sorted(словарь.items(), key=lambda пара: -пара[1])[:сколько]


# --------------------------------------------------------------------------
# ДЕЛО 0. Реквизиты агентства
# --------------------------------------------------------------------------

# Пока готовишь файл - работай на сэмпле, он маленький и быстрый:
# файл = "game_server.log"
файл = "game_server_full.log"

# Серверы: Рил[Мир], Голд[Мир], Просто[Мир], Алмаз[Мир], Добро[Мир], Игро[Мир]
мой_сервер = ""                     # TODO 1: впиши свой сервер (в кавычках!)

# Сколько обменов считаем "часто меняется" (для полного лога)
порог_обменов = 30                  # для сэмпла game_server.log поставь 2


# --------------------------------------------------------------------------
# ШАГ 1. Только строки нашего сервера
#   Инструменты: for, split(" - "), поля[1], if, +=
# --------------------------------------------------------------------------

всего = 0
у_меня = 0

for строка in open(файл, encoding="utf-8"):
    всего += 1
    поля = строка.split(" - ")          # режем строку на 7 полей
    if поля[1] == мой_сервер:           # TODO 2: это строка МОЕГО сервера?
        у_меня += 1

print("Всего строк в логе:", всего)
print("Строк моего сервера:", у_меня)


# --------------------------------------------------------------------------
# ШАГ 2. Только столицы и города: злодей не торгует в деревнях
#   Инструменты: in, or, continue
# --------------------------------------------------------------------------

подходящих = 0

for строка in open(файл, encoding="utf-8"):
    поля = строка.split(" - ")
    if поля[1] != мой_сервер:           # чужой сервер - пропускаем строку
        continue
    if "(столица)" in поля[2] or "(город)" in поля[2]:      # TODO 3: столица ИЛИ город?
        подходящих += 1

print("Строк в столицах и городах моего сервера:", подходящих)


# --------------------------------------------------------------------------
# ШАГ 3. Кто говорил про золото? (корни "золот" и "голд")
#   Инструменты: словарь-счётчик, .get(), strip('"')
#   ВНИМАНИЕ: список будет БОЛЬШОЙ - злодей прячется в шуме!
# --------------------------------------------------------------------------

говорили_о_золоте = {}

for строка in open(файл, encoding="utf-8"):
    поля = строка.split(" - ")
    if поля[1] != мой_сервер:
        continue
    if "(столица)" not in поля[2] and "(город)" not in поля[2]:
        continue
    ник = поля[3]
    действие = поля[4].strip('"')           # снимаем кавычки: "сказал" -> сказал
    сообщение = поля[6].strip('"')          # снимаем кавычки с сообщения
    if действие == "сказал" and ("золот" in сообщение or "голд" in сообщение):  # TODO 4
        говорили_о_золоте[ник] = говорили_о_золоте.get(ник, 0) + 1             # TODO 5

print("Про золото говорили", len(говорили_о_золоте), "игроков! Топ-5 болтунов:")
print(топ(говорили_о_золоте))


# --------------------------------------------------------------------------
# ШАГ 4. Кто часто меняется? (действие "обмен")
#   Фильтр тот же: мой сервер + столица/город
# --------------------------------------------------------------------------

менялись = {}

for строка in open(файл, encoding="utf-8"):
    поля = строка.split(" - ")
    if поля[1] != мой_сервер:
        continue
    if "(столица)" not in поля[2] and "(город)" not in поля[2]:
        continue
    ник = поля[3]
    действие = поля[4].strip('"')
    if действие == "обмен":                 # TODO 6: это обмен?
        менялись[ник] = менялись.get(ник, 0) + 1

print("Топ-5 по обменам:")
print(топ(менялись))


# --------------------------------------------------------------------------
# ШАГ 5. Пересекаем: про золото И часто меняется = ПОДОЗРЕВАЕМЫЕ
#   Инструменты: for по словарю, in, >=
# --------------------------------------------------------------------------

подозреваемые = []

for ник in менялись:
    if менялись[ник] >= порог_обменов and ник in говорили_о_золоте:     # TODO 7
        подозреваемые.append(ник)

print("Подозреваемые:", подозреваемые)


# --------------------------------------------------------------------------
# ШАГ 6. Кому пишут в лс много РАЗНЫХ людей?
#   Инструменты: множество set, .add(), len()
# --------------------------------------------------------------------------

авторы_лс = {}

for строка in open(файл, encoding="utf-8"):
    поля = строка.split(" - ")
    if поля[1] != мой_сервер:
        continue
    действие = поля[4].strip('"')
    if действие != "написал_в_лс":          # TODO 8: нам нужны только лс
        continue
    автор = поля[3]
    цель = поля[5]
    if цель not in авторы_лс:
        авторы_лс[цель] = set()             # заводим пустое множество авторов
    авторы_лс[цель].add(автор)              # добавляем автора в множество

рейтинг_лс = {}
for цель in авторы_лс:
    рейтинг_лс[цель] = len(авторы_лс[цель])     # TODO 9: сколько РАЗНЫХ авторов?

print("Топ-4 по числу авторов лс:")
print(топ(рейтинг_лс, 4))


# --------------------------------------------------------------------------
# ШАГ 7. ДОСЬЕ: где побывали подозреваемые за весь день 9 мая?
#   Злодей никуда не уходит - он весь день стоит в столице!
# --------------------------------------------------------------------------

# TODO 10: впиши сюда имена подозреваемых из шагов 5 и 6
#          (в <скобках>, точно как их печатает программа)
подозреваемые = ["<имя1>", "<имя2>", "<имя3>"]

где_были = {}

for строка in open(файл, encoding="utf-8"):
    поля = строка.split(" - ")
    ник = поля[3]
    if ник in подозреваемые:                # TODO 11: только подозреваемые!
        if ник not in где_были:
            где_были[ник] = set()
        где_были[ник].add(поля[2])

print()
print("Досье за весь день 9 мая:")
for ник in где_были:
    места = где_были[ник]
    print(ник, "- был в", len(места), "разных местах:", sorted(места))

# TODO 12: вынеси вердикт! Кто из подозреваемых был только в ОДНОМ месте?
# print("ДЕЛО ЗАКРЫТО! Злодей на сервере", мой_сервер, "- это ...")


# --------------------------------------------------------------------------
# ШАГ 8. БОНУС СЫЩИКА: на какой сайт злодей заманивал игроков?
# --------------------------------------------------------------------------

for строка in open(файл, encoding="utf-8"):
    if "базар" in строка and мой_сервер in строка:      # TODO 13 (бонус)
        print(строка)
