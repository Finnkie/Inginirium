# --------------------------------------------------------------------------
# ИНСТРУМЕНТ СЫЩИКА
# --------------------------------------------------------------------------

def топ(словарь, сколько=5):
    """Из словаря {имя: число} возвращает топ самых-самых."""
    return sorted(словарь.items(), key=lambda пара: -пара[1])[:сколько]


# --------------------------------------------------------------------------
# ДЕЛО 0. Реквизиты агентства
# --------------------------------------------------------------------------

файл = "game_server_full.log"       # для быстрой отладки: "game_server.log"

мой_сервер = "Голд[Мир]"            # TODO 1 (решение)

порог_обменов = 30                  # для сэмпла game_server.log - 2


# --------------------------------------------------------------------------
# ШАГ 1. Только строки нашего сервера
# --------------------------------------------------------------------------

всего = 0
у_меня = 0

for строка in open(файл, encoding="utf-8"):
    всего += 1
    поля = строка.split(" - ")
    if поля[1] == мой_сервер:               # TODO 2 (решение)
        у_меня += 1

print("Всего строк в логе:", всего)
print("Строк моего сервера:", у_меня)


# --------------------------------------------------------------------------
# ШАГ 2. Только столицы и города
# --------------------------------------------------------------------------

подходящих = 0

for строка in open(файл, encoding="utf-8"):
    поля = строка.split(" - ")
    if поля[1] != мой_сервер:
        continue
    if "(столица)" in поля[2] or "(город)" in поля[2]:      # TODO 3 (решение)
        подходящих += 1

print("Строк в столицах и городах моего сервера:", подходящих)


# --------------------------------------------------------------------------
# ШАГ 3. Кто говорил про золото?
# --------------------------------------------------------------------------

говорили_о_золоте = {}

for строка in open(файл, encoding="utf-8"):
    поля = строка.split(" - ")
    if поля[1] != мой_сервер:
        continue
    if "(столица)" not in поля[2] and "(город)" not in поля[2]:
        continue
    ник = поля[3]
    действие = поля[4].strip('"')
    сообщение = поля[6].strip('"')
    if действие == "сказал" and ("золот" in сообщение or "голд" in сообщение):  # TODO 4 (решение)
        говорили_о_золоте[ник] = говорили_о_золоте.get(ник, 0) + 1              # TODO 5 (решение)

print("Про золото говорили", len(говорили_о_золоте), "игроков! Топ-5 болтунов:")
print(топ(говорили_о_золоте))


# --------------------------------------------------------------------------
# ШАГ 4. Кто часто меняется?
# --------------------------------------------------------------------------

менялись = {}

for строка in open(файл, encoding="utf-8"):
    поля = строка.split(" - ")
    if поля[1] != мой_сервер:
        continue
    if "(столица)" not in поля[2] and "(город)" not in поля[2]:
        continue
    ник = поля[3]
    действие = поля[4].strip('"')
    if действие == "обмен":                 # TODO 6 (решение)
        менялись[ник] = менялись.get(ник, 0) + 1

print("Топ-5 по обменам:")
print(топ(менялись))


# --------------------------------------------------------------------------
# ШАГ 5. Пересечение -> подозреваемые
# --------------------------------------------------------------------------

подозреваемые = []

for ник in менялись:
    if менялись[ник] >= порог_обменов and ник in говорили_о_золоте:     # TODO 7 (решение)
        подозреваемые.append(ник)

print("Подозреваемые:", подозреваемые)


# --------------------------------------------------------------------------
# ШАГ 6. Кому пишут в лс много разных людей?
# --------------------------------------------------------------------------

авторы_лс = {}

for строка in open(файл, encoding="utf-8"):
    поля = строка.split(" - ")
    if поля[1] != мой_сервер:
        continue
    действие = поля[4].strip('"')
    if действие != "написал_в_лс":          # TODO 8 (решение)
        continue
    автор = поля[3]
    цель = поля[5]
    if цель not in авторы_лс:
        авторы_лс[цель] = set()
    авторы_лс[цель].add(автор)

рейтинг_лс = {}
for цель in авторы_лс:
    рейтинг_лс[цель] = len(авторы_лс[цель])     # TODO 9 (решение)

print("Топ-4 по числу авторов лс:")
print(топ(рейтинг_лс, 4))


# --------------------------------------------------------------------------
# ШАГ 7. ДОСЬЕ: кто весь день стоит в столице?
# --------------------------------------------------------------------------

# TODO 10 (решение): имена берём из шагов 5 и 6 - для Голд[Мир] это:
подозреваемые = ["<ДобрыйЖук>", "<СкупщикРадя>", "<ПерекупНикита>", "<МенялаГриша>"]

где_были = {}

for строка in open(файл, encoding="utf-8"):
    поля = строка.split(" - ")
    ник = поля[3]
    if ник in подозреваемые:                # TODO 11 (решение)
        if ник not in где_были:
            где_были[ник] = set()
        где_были[ник].add(поля[2])

print()
print("Досье за весь день 9 мая:")
злодей = ""
for ник in где_были:
    места = где_были[ник]
    print(ник, "- был в", len(места), "разных местах:", sorted(места))
    if len(места) == 1:
        злодей = ник                        # тот, кто весь день в одном месте!

# TODO 12 (решение): вердикт
print()
print("ДЕЛО ЗАКРЫТО! Злодей на сервере", мой_сервер, "- это", злодей)


# --------------------------------------------------------------------------
# ШАГ 8. БОНУС: сайт злодея + все его крики о золоте за день (улики)
# --------------------------------------------------------------------------

print()
print("УЛИКИ. Сайт, куда он заманивал игроков:")
for строка in open(файл, encoding="utf-8"):
    if "базар" in строка and мой_сервер in строка:      # TODO 13 (решение)
        print(" ", строка)

print()
print("УЛИКИ. Что кричал злодей весь день:")
for строка in open(файл, encoding="utf-8"):
    поля = строка.split(" - ")
    if поля[3] == злодей and поля[4] == '"сказал"':
        сообщение = поля[6].strip('"')
        if "золот" in сообщение or "голд" in сообщение:
            print(" ", строка)
